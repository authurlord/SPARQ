import pandas as pd
df = pd.read_csv('table.csv')
print("The table contains information about power plants in India, including:")
print("- sno: Serial number of the power plant")
print("- power plant: Name of the power plant")
print("- state: State where the power plant is located")
print("- commissioned capacity (mw): Total electricity generation capacity in megawatts (MW)")
print("- year of commission: Year when the power plant was commissioned")
total_plants = len(df)
print(f"\nTotal number of power plants: {total_plants}")
capacity_summary = df['commissioned capacity (mw)'].describe()
print(f"Capacity summary (in MW):")
print(f"  Minimum: {capacity_summary['min']}")
print(f"  Maximum: {capacity_summary['max']}")
print(f"  Mean: {capacity_summary['mean']:.1f}")
print(f"  Median: {capacity_summary['50%']}")
state_counts = df['state'].value_counts()
print("\nTop states by number of power plants:")
print(state_counts.head())