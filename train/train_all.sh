#!/bin/bash

# 主训练脚本 - 依次训练所有模型
# 在 base 环境中运行

echo "=========================================="
echo "开始训练不同样本数量的模型"
echo "=========================================="

# 激活 base 环境
source ~/.bashrc
conda activate base

# 进入训练目录
cd /data/workspace/yanmy/SPARQ/train

# 训练 20 样本模型
echo ""
echo "=========================================="
